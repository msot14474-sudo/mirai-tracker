// Derive the AI's screen vocabulary from the same source shipped to users.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const ts = require('typescript');
const root = path.resolve(__dirname, '../../web/src');
const screens = [];
for (const file of fs.readdirSync(root).filter(f => f.endsWith('.tsx') && !f.includes('.test.')).sort()) {
  const source = fs.readFileSync(path.join(root, file), 'utf8');
  const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const labels = new Set();
  function walk(node) {
    if (ts.isJsxElement(node) && /^(h[1-4]|label|button|summary)$/.test(node.openingElement.tagName.getText(ast))) {
      const text = node.children.filter(ts.isJsxText).map(n => n.text).join(' ').replace(/\s+/g, ' ').trim();
      if (text.length > 2 && text.length < 180) labels.add(text);
    }
    if (ts.isPropertyAssignment(node) && node.name.getText(ast) === 'label' && ts.isStringLiteral(node.initializer)) labels.add(node.initializer.text);
    ts.forEachChild(node, walk);
  }
  walk(ast);
  if (labels.size) screens.push({ screen: file.replace('.tsx', ''), controls: [...labels].slice(0, 28) });
}
const version = crypto.createHash('sha256').update(JSON.stringify(screens)).digest('hex').slice(0, 12);
fs.writeFileSync(path.resolve(__dirname, '../src/ai-insights/app-screens.generated.ts'), `// Generated by scripts/generate-ai-guide.cjs on every build; do not edit.\nexport const appScreens = ${JSON.stringify({version, screens}, null, 2)} as const;\n`);
